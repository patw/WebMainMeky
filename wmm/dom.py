"""DOM parsing, normalization, and structural statistics.

Everything here is deterministic. No model, no network.
"""
from __future__ import annotations

import re
from collections import Counter

from lxml import html as lxml_html

BLOCK_TAGS = {
    'p', 'div', 'section', 'article', 'main', 'header', 'footer', 'aside',
    'ul', 'ol', 'li', 'table', 'pre', 'blockquote', 'h1', 'h2', 'h3', 'h4',
    'h5', 'h6', 'figure', 'dl', 'form', 'fieldset', 'center', 'address',
    'dd', 'dt', 'caption', 'figcaption', 'body', 'html', 'nav',
}
SKIP_TAGS = {
    'script', 'style', 'noscript', 'iframe', 'svg', 'canvas', 'button',
    'select', 'option', 'textarea', 'input', 'label', 'video', 'audio',
    'source', 'track', 'picture', 'map', 'object', 'embed', 'link', 'meta',
    'head', 'title', 'form', 'nav',
}
HEADINGS = {'h1': 1, 'h2': 2, 'h3': 3, 'h4': 4, 'h5': 5, 'h6': 6}

CHROME_KW = re.compile(
    r'nav|header|footer|sidebar|side-bar|menu|breadcrumb|pagination|pager|comment|'
    r'reply|share|social|subscribe|newsletter|cookie|consent|advert|sponsor|promo|'
    r'related|recommend|popular|trending|recent-post|category|categories|tag-|'
    r'-tag|tags|search|login|signin|register|account|user-menu|cart|shop-cart|'
    r'searchbox|toolbar|banner|popup|modal|overlay|disclaimer|copyright|crumbs|'
    r'topbar|hero|carousel|slider|widget|footer-|-footer|header-|-header', re.I)
CONTENT_KW = re.compile(
    r'article|post|entry|content|body|text|story|detail|main|description|'
    r'readme|doc|paragraph|prose', re.I)

# class/id tokens that carry no meaning (generated by CSS frameworks)
GENERATED_TOKEN = re.compile(
    r'^(sc|css|jsx|ng|Sxl|css-|_)[a-z0-9_-]*$|^[a-z]+-[a-z0-9]{4,}$|.*[0-9a-f]{6,}$|'
    r'^[a-z]+-[0-9]+$', re.I)
HAS_DIGIT_RUN = re.compile(r'\d{3,}')


def parse_html(html_str: str):
    """Parse with recovery; returns the root element (never raises on messy input)."""
    if isinstance(html_str, str) and (
            '<?xml' in html_str or '<meta charset' in html_str or 'encoding=' in html_str):
        html_str = html_str.encode('utf-8', 'replace')
    parser = lxml_html.HTMLParser(
        collect_ids=False, encoding='utf-8', remove_blank_text=True,
        remove_comments=True, remove_pis=True)
    return lxml_html.fromstring(html_str, parser=parser)


def normalize_tokens(el) -> list[str]:
    """Semantic class/id tokens only: generated framework hashes are dropped."""
    raw = f"{el.get('class', '')} {el.get('id', '')} {el.get('role', '')}"
    tokens = []
    for tok in raw.split():
        tok = tok.strip().lower()
        if len(tok) < 3 or len(tok) > 40:
            continue
        if GENERATED_TOKEN.match(tok) or HAS_DIGIT_RUN.search(tok):
            continue
        if re.fullmatch(r'[0-9a-f]{5,}', tok):
            continue
        tokens.append(tok)
    return tokens


def semantic_tokens(el) -> set[str]:
    return set(normalize_tokens(el))


def attrs_id(el) -> str:
    return f"{el.get('class', '')} {el.get('id', '')} {el.get('role', '')}"


def is_chrome(el) -> bool:
    if not isinstance(getattr(el, 'tag', None), str):
        return False
    # semantic elements are chrome by definition; generic containers are judged
    # by their class/id keywords
    if el.tag in ('nav', 'form', 'aside', 'header', 'footer'):
        return True
    a = attrs_id(el)
    if not a.strip():
        return False
    return bool(CHROME_KW.search(a)) and not CONTENT_KW.search(a)


def hidden(el) -> bool:
    st = el.get('style', '') or ''
    return 'display: none' in st or 'display:none' in st


def text_len(el) -> int:
    return len(el.text_content().strip())


def link_len(el) -> int:
    return sum(len(a.text_content().strip()) for a in el.iter('a'))


def link_density(el) -> float:
    tl = text_len(el)
    return (link_len(el) / tl) if tl else 1.0


def block_elements(root, max_depth: int = 24):
    """Yield block-level elements in document order, depth-limited."""
    for el in root.iter():
        if not isinstance(getattr(el, 'tag', None), str):
            continue
        if el.tag not in BLOCK_TAGS:
            continue
        depth = len(el.getroottree().getpath(el).split('/'))
        if depth > max_depth:
            continue
        yield el, depth


def landmark_score(el) -> float:
    """schema.org / semantic HTML landmarks give a free prior on the content region."""
    score = 0.0
    tag = el.tag
    if tag == 'article':
        score += 1.0
    if tag == 'main':
        score += 1.2
    if el.get('itemprop') and 'articlebody' in el.get('itemprop').lower():
        score += 1.5
    if el.get('role') == 'main':
        score += 1.2
    if el.get('itemprop') in ('articleBody', 'articleBody'.lower()):
        score += 1.5
    toks = semantic_tokens(el)
    if toks & {'article', 'post', 'entry', 'story', 'content', 'prose', 'body', 'detail'}:
        score += 0.8
    if is_chrome(el):
        score -= 1.2
    return score


def jsonld_types(html_str: str) -> list[str]:
    """Extract @type values from ld+json blocks (cheap regex, no JSON parse required)."""
    out = []
    for m in re.finditer(r'<script[^>]*type=["\']application/ld\+json["\'][^>]*>(.*?)</script>',
                         html_str, re.S | re.I):
        out.extend(re.findall(r'"@type"\s*:\s*"([^"]+)"', m.group(1)))
    return out


def og_title(html_str: str) -> str:
    m = re.search(r'<meta[^>]+property=["\']og:title["\'][^>]*content=["\']([^"\']*)["\']',
                  html_str, re.I)
    if not m:
        m = re.search(r'<meta[^>]+content=["\']([^"\']*)["\'][^>]*property=["\']og:title["\']',
                      html_str, re.I)
    return m.group(1).strip() if m else ''


def page_title(root) -> str:
    t = root.find('.//title')
    return (t.text or '').strip() if t is not None else ''


def token_counter(root) -> Counter:
    c = Counter()
    for el, _ in block_elements(root):
        c[el.tag] += 1
    return c
